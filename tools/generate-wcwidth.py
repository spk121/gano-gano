#!/usr/bin/env python3
"""
Generate src/gano/wcwidth.scm: terminal display widths of Unicode characters.

Widths follow Markus Kuhn's wcwidth() (the behaviour of glibc and xterm):

   -1  C0/C1 control characters (Cc) and surrogates (Cs)
    0  NUL; nonspacing and enclosing marks (Mn, Me); format characters
       (Cf) except SOFT HYPHEN; ZERO WIDTH SPACE; Hangul Jamo medial
       vowels and final consonants (U+1160..U+11FF, U+D7B0..U+D7FF)
    2  East Asian Wide (W) and Fullwidth (F)
  1|2  East Asian Ambiguous (A), including private use: 2 in CJK mode
    1  everything else (including spacing marks, Mc)

The Unicode data comes from Python's unicodedata module by default, so no
network access is needed.  To use another Unicode version, pass local copies
of UnicodeData.txt and EastAsianWidth.txt (their First>/Last> and ".."
ranges are expanded properly).

Usage:
    python3 tools/generate-wcwidth.py [-o src/gano/wcwidth.scm]
    python3 tools/generate-wcwidth.py --unicode-data UnicodeData.txt \
        --east-asian-width EastAsianWidth.txt [-o ...]
"""

import argparse
import re
import sys
import unicodedata

MAX_CP = 0x10FFFF

ZERO_WIDTH_EXTRA = [(0x200B, 0x200B), (0x1160, 0x11FF), (0xD7B0, 0xD7FF)]
SOFT_HYPHEN = 0x00AD


# ---------------------------------------------------------------------
# Data sources: each returns (category(cp), east_asian_width(cp), version)

def python_source():
    def category(cp):
        return unicodedata.category(chr(cp))

    def eaw(cp):
        return unicodedata.east_asian_width(chr(cp))

    return category, eaw, unicodedata.unidata_version


def file_source(unicode_data_path, eaw_path):
    categories = {}
    with open(unicode_data_path, encoding="utf-8") as f:
        first = None
        for line in f:
            fields = line.rstrip("\n").split(";")
            if len(fields) < 3:
                continue
            cp, name, cat = int(fields[0], 16), fields[1], fields[2]
            if name.endswith(", First>"):
                first = cp
            elif name.endswith(", Last>"):
                for c in range(first, cp + 1):
                    categories[c] = cat
                first = None
            else:
                categories[cp] = cat

    widths = {}
    version = None
    with open(eaw_path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.search(r"EastAsianWidth-(\d+\.\d+\.\d+)", line)
                if m:
                    version = m.group(1)
            data = line.split("#")[0].strip()
            if not data or ";" not in data:
                continue
            cps, w = (s.strip() for s in data.split(";", 1))
            lo, _, hi = cps.partition("..")
            for c in range(int(lo, 16), int(hi or lo, 16) + 1):
                widths[c] = w

    return (lambda cp: categories.get(cp, "Cn"),
            lambda cp: widths.get(cp, "N"),
            version or "unknown")


# ---------------------------------------------------------------------

def classify(cp, category, eaw):
    """One of 'control', 'zero', 'wide', 'ambiguous' or None (width 1)."""
    if cp == 0:
        return "zero"
    cat = category(cp)
    if cat in ("Cc", "Cs"):
        return "control"
    if cat in ("Mn", "Me") or (cat == "Cf" and cp != SOFT_HYPHEN) \
            or any(lo <= cp <= hi for lo, hi in ZERO_WIDTH_EXTRA):
        return "zero"
    w = eaw(cp)
    if w in ("W", "F"):
        return "wide"
    if w == "A":
        return "ambiguous"
    return None


def build_tables(category, eaw):
    tables = {"control": [], "zero": [], "wide": [], "ambiguous": []}
    current, start = None, 0
    for cp in range(MAX_CP + 2):
        kind = classify(cp, category, eaw) if cp <= MAX_CP else None
        if kind != current:
            if current is not None:
                tables[current].append((start, cp - 1))
            current, start = kind, cp
    return tables


def scheme_vector(name, ranges, comment):
    items = [f"(#x{lo:04X} . #x{hi:04X})" for lo, hi in ranges]
    lines, line = [], "  "
    for item in items:
        if len(line) + len(item) + 1 > 76:
            lines.append(line.rstrip())
            line = "  "
        line += item + " "
    lines.append(line.rstrip())
    body = "\n".join(lines)
    return f";; {comment}\n(define {name}\n  #(\n{body}))\n"


def generate(tables, version):
    out = [f""";;; wcwidth.scm - Unicode character width calculation
;;;
;;; GENERATED by tools/generate-wcwidth.py from Unicode {version} data.
;;; Do not edit by hand; edit and re-run the generator instead.
;;;
;;; Widths follow Markus Kuhn's wcwidth() (the behaviour of glibc and
;;; xterm); see the generator for the exact rules.

(define-module (gano wcwidth)
  #:export (wcwidth
            wcwidth-unicode-version))

(define wcwidth-unicode-version "{version}")

;;; =================================================================
;;; UNICODE LOOKUP TABLES (sorted vectors of inclusive ranges)
;;; =================================================================
"""]
    out.append(scheme_vector("control-ranges", tables["control"],
                             "Width -1: control characters (Cc) and surrogates (Cs)"))
    out.append(scheme_vector("zero-width-ranges", tables["zero"],
                             "Width 0: Mn, Me, Cf (except U+00AD), U+200B, Hangul Jamo vowels/finals"))
    out.append(scheme_vector("wide-ranges", tables["wide"],
                             "Width 2: East Asian Wide and Fullwidth"))
    out.append(scheme_vector("ambiguous-ranges", tables["ambiguous"],
                             "Width 1, or 2 in CJK mode: East Asian Ambiguous (includes private use)"))
    out.append(""";;; =================================================================
;;; LOOKUP
;;; =================================================================

(define (in-ranges? ucs ranges)
  "Binary search for UCS in a sorted vector of (start . end) ranges"
  (let loop ([lo 0] [hi (- (vector-length ranges) 1)])
    (and (<= lo hi)
         (let* ([mid (quotient (+ lo hi) 2)]
                [range (vector-ref ranges mid)])
           (cond
            [(< ucs (car range)) (loop lo (- mid 1))]
            [(> ucs (cdr range)) (loop (+ mid 1) hi)]
            [else #t])))))

(define* (wcwidth x #:optional (cjk #f))
  "Display width of a character, codepoint or string in terminal cells:
     -1  control characters (C0, DEL, C1) and surrogates
      0  NUL, nonspacing/enclosing marks, format characters (except SOFT
         HYPHEN), ZERO WIDTH SPACE, Hangul Jamo medial vowels and finals
      2  East Asian Wide and Fullwidth characters
      1  everything else; East Asian Ambiguous characters (including
         private use) are 2 instead when CJK is true.
   A string's width is the sum of its characters' widths, or -1 if it
   contains a control character.  Anything else gives -1."
  (cond
   [(string? x)
    (let loop ([i 0] [total 0])
      (if (= i (string-length x))
          total
          (let ([w (wcwidth (string-ref x i) cjk)])
            (if (< w 0) -1 (loop (+ i 1) (+ total w))))))]
   [(char? x) (wcwidth (char->integer x) cjk)]
   [(and (exact-integer? x) (<= 0 x #x10FFFF))
    (cond
     [(= x 0) 0]
     [(< x 127) (if (< x 32) -1 1)]          ; fast path for ASCII
     [(in-ranges? x control-ranges) -1]
     [(in-ranges? x zero-width-ranges) 0]
     [(in-ranges? x wide-ranges) 2]
     [(in-ranges? x ambiguous-ranges) (if cjk 2 1)]
     [else 1])]
   [else -1]))
""")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-o", "--output", default="src/gano/wcwidth.scm")
    parser.add_argument("--unicode-data", help="local UnicodeData.txt")
    parser.add_argument("--east-asian-width", help="local EastAsianWidth.txt")
    args = parser.parse_args()

    if bool(args.unicode_data) != bool(args.east_asian_width):
        parser.error("give both --unicode-data and --east-asian-width, or neither")
    if args.unicode_data:
        category, eaw, version = file_source(args.unicode_data, args.east_asian_width)
    else:
        category, eaw, version = python_source()

    tables = build_tables(category, eaw)
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(generate(tables, version))
    counts = ", ".join(f"{k} {len(v)}" for k, v in tables.items())
    print(f"Wrote {args.output} (Unicode {version}; ranges: {counts})", file=sys.stderr)


if __name__ == "__main__":
    main()
